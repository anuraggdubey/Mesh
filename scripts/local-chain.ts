// Local rehearsal chain: starts anvil, deploys the Mesh contracts, registers and stakes two provider wallets, writes
// `.env.localchain` (git-ignored) and keeps running until Ctrl+C.
//
//   npm run chain:local
//   npx tsx scripts/with-env.ts .env.localchain -- npx next dev -p 3200      # API against the local chain
//
// Everything uses the public anvil test keys: free, instant, and worthless on any real network.
import { writeFileSync } from "node:fs";
import { LOCAL_CHAIN_ID, foundryAvailable, foundryBinDir, startLocalChain } from "../src/lib/local-chain";
import { ANVIL_KEYS } from "../src/lib/local-chain";

async function main() {
  if (!foundryAvailable()) {
    console.error(`Foundry (anvil + forge) not found in ${foundryBinDir()}. Install it or set FOUNDRY_BIN.`);
    process.exit(1);
  }
  const port = Number(process.env.LOCAL_CHAIN_PORT ?? 8545);
  console.log(`starting anvil on port ${port} and deploying the contracts...`);
  const chain = await startLocalChain({ blockTimeSeconds: 2, port, windowSeconds: Number(process.env.LOCAL_WINDOW_SECONDS ?? 15), provisionProviders: [ANVIL_KEYS[3], ANVIL_KEYS[4]], stakeEther: "1" });

  const env = [
    "# generated by scripts/local-chain.ts: local anvil rehearsal values. Safe to delete.",
    `HEDERA_RPC_URL=${chain.rpcUrl}`,
    `HEDERA_CHAIN_ID=${LOCAL_CHAIN_ID}`,
    `STAKE_ADDRESS=${chain.contracts.stake}`,
    `ESCROW_ADDRESS=${chain.contracts.escrow}`,
    `RECEIPT_ADDRESS=${chain.contracts.receipt}`,
    `PAYMENT_TOKEN_ADDRESS=${chain.contracts.token}`,
    `API_PRIVATE_KEY=${chain.keys.api}`,
    `VERIFIER_PRIVATE_KEY=${chain.keys.verifier}`,
    `MIN_STAKE_WEI=1000000000000000000`,
    `MESH_DEV_SKIP_PAYMENT=true`,
    `MESH_DEV_SKIP_WORLD=true`,
    `MESH_CHAIN_LOOP=true`,
    `MESH_DEV_AUTO_APPROVE=true`, // DEV ONLY: no verifier yet, so finalize after the window without a spot-check
    `DATA_DIR=./data/localchain`,
    "",
  ].join("\n");
  writeFileSync(".env.localchain", env);
  // separate provider env so the real worker can be started with the same trick
  writeFileSync(
    ".env.localchain.providerA",
    [`PROVIDER_PRIVATE_KEY=${chain.keys.providerA}`, `API_PUBLIC_URL=${process.env.LOCAL_API_URL ?? "http://localhost:3200"}`, ""].join("\n"),
  );
  writeFileSync(
    ".env.localchain.providerB",
    [`PROVIDER_PRIVATE_KEY=${chain.keys.providerB}`, `API_PUBLIC_URL=${process.env.LOCAL_API_URL ?? "http://localhost:3200"}`, ""].join("\n"),
  );

  console.log(`\nlocal chain ready at ${chain.rpcUrl} (chain ${chain.chainId})`);
  console.log(`  stake   ${chain.contracts.stake}\n  escrow  ${chain.contracts.escrow}\n  receipt ${chain.contracts.receipt}\n  token   ${chain.contracts.token}`);
  console.log(`  providers registered and staked 1 ETH each: ${chain.addresses.providerA}, ${chain.addresses.providerB}`);
  console.log("\nwrote .env.localchain, .env.localchain.providerA, .env.localchain.providerB. Ctrl+C stops the chain.");

  const stop = () => {
    chain.stop();
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);
  await new Promise(() => {}); // keep anvil alive
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
